def normalize(path: Path, replacements: dict[str, str], check: bool) -> list[str]:
    text = path.read_text(encoding="utf-8")
    updated = text
    unresolved: list[str] = []
    for old, new in replacements.items():
        if old in updated:
            updated = updated.replace(old, new)
    if check:
        if updated != text:
            unresolved.append("normalization required")
    elif updated != text:
        path.write_text(updated, encoding="utf-8")
    return unresolved


